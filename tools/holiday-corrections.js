/* RUN: node tools/holiday-corrections.js
   ---------------------------------------------------------------------------
   Re-applies every hand-verified correction to the generated holiday data.

   WHY THIS FILE IS THE IMPORTANT ONE

   The holiday data is generated by tools/extract-holidays.py from the Python
   `holidays` library. Corrections made by editing assets/holidays/*.js by hand
   survive exactly until the next regeneration, and then vanish silently. There
   is no error, no conflict, no diff anyone reads: the calendar simply goes
   back to being wrong, months later, for the same reasons as before.

   So the corrections live here instead, as code, and the pipeline is:

       1. node tools/extract-holidays.py   (or the Colab notebook)
       2. node tools/holiday-corrections.js
       3. node tools/audit-holidays.js     <- fails if step 2 was skipped

   Running this file twice is safe. It reports what it changed, and changes
   nothing when the data is already correct.

   WHAT IS BEING CORRECTED, AND WHY THE GENERATOR GETS IT WRONG

   Fault 1: "national" means "every subdivision".
     The library defines a country-level holiday set and then adds subdivision
     extras on top. Anything not observed in EVERY subdivision lands in the
     extras and is therefore marked regional, and regional days are hidden by
     default. That is how Easter Monday and the late-August bank holiday
     disappeared for UK users: Scotland does something else, so three of the
     four nations and about 97% of the population were outvoted.

   Fault 2: a holiday deleted for falling on a weekend.
     Generated with observed=True, the library substitutes the observed day for
     the real one in some countries rather than adding it. Spain lost nine of
     its ten fixed national holidays in any year they fell on a Sunday.
     Christmas Day was absent from the Spanish calendar in 2016, 2022, 2033,
     2039 and 2044. extract-holidays.py now generates both sets and unions
     them, but this file repairs data produced by the old script too.

   Fault 3: a legal technicality that is useless in a calendar.
     Swedish law classes every Sunday as a public holiday. Perfectly true, and
     it painted the whole Sunday column red for 31 years while burying the
     eleven days a Swede actually plans around.
   --------------------------------------------------------------------------- */
const fs   = require("fs");
const path = require("path");
const DIR  = path.resolve(__dirname, "..", "assets", "holidays");

/* --------------------------------------------------------------- the rules */

/* Days observed by the overwhelming majority of a country, demoted by fault 1.
   Each one is a bank holiday for at least three of the UK's four nations. Add
   to this list only after checking an official source, and say which. */
const PROMOTE_TO_NATIONAL = {
  /* gov.uk bank holidays: both apply in England, Wales and Northern Ireland.
     Scotland's own early-August "Summer Bank Holiday" is NOT here and must
     stay regional, because it genuinely is Scotland only. */
  GB: [/^Easter Monday$/, /^Late Summer Bank Holiday$/],
  /* Australia Day is a public holiday in every state and territory. When
     26 January is a Sunday the entire country takes the Monday. The King's
     Birthday is NOT here: its date differs by state, so regional is right. */
  AU: [/^Australia Day$/]
};

/* Fixed-date national holidays that the generator deleted whenever they fell
   on a weekend. A fixed-date holiday does not stop existing because of what
   weekday it lands on. Restored on its own real date; the regional
   "Monday following X" entries are left alone, because which communities
   actually take the Monday does vary. */
const RESTORE_FIXED = {
  ES: ["0101","0106","0501","0815","1012","1101","1206","1208","1225"],
  RO: ["0124"],
  JE: ["0509"],
  GI: ["0910"]
};

/* Names that are not holidays. */
const WEEKDAY = /^(Sunday|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday)$/;
const DROP_WEEKDAY_NAMES = ["SE"];

/* ------------------------------------------------------------------ plumbing */

function read(code){
  const file = path.join(DIR, code + ".js");
  if (!fs.existsSync(file)) return null;
  const src = fs.readFileSync(file, "utf8");
  const m = src.match(/^window\.__imcHol&&window\.__imcHol\("([A-Z]{2})",(\{[\s\S]*\})\);\s*$/);
  if (!m) throw new Error(code + ": unexpected file shape, refusing to touch it");
  return JSON.parse(m[2]);
}
function write(code, data){
  fs.writeFileSync(path.join(DIR, code + ".js"),
    'window.__imcHol&&window.__imcHol("' + code + '",' + JSON.stringify(data) + ');\n');
}

let total = 0;
const report = [];

/* ---- 1. promote days the majority of the country observes ---------------- */
for (const code in PROMOTE_TO_NATIONAL){
  const data = read(code);
  if (!data) continue;
  let n = 0;
  for (const year in data) for (const key in data[year]){
    const entry = data[year][key];
    if (entry[1] === 1 && PROMOTE_TO_NATIONAL[code].some(re => re.test(entry[0]))){
      entry[1] = 0; n++;
    }
  }
  if (n){ write(code, data); total += n; report.push(code + ": promoted " + n + " days to national"); }
}

/* ---- 2. restore fixed dates deleted for landing on a weekend -------------- */
for (const code in RESTORE_FIXED){
  const data = read(code);
  if (!data) continue;
  const years = Object.keys(data).map(Number).sort((a,b) => a - b);
  let n = 0;
  for (const key of RESTORE_FIXED[code]){
    /* take the name from a year where the day survived, so nothing is invented */
    let name = null;
    for (const y of years){
      const e = data[String(y)][key];
      if (e && e[1] !== 1){ name = e[0]; break; }
    }
    if (!name){ report.push(code + " " + key + ": no surviving example to copy a name from, skipped"); continue; }
    for (const y of years){
      if (data[String(y)][key]) continue;
      data[String(y)][key] = [name, 0];
      n++;
    }
  }
  if (n){ write(code, data); total += n; report.push(code + ": restored " + n + " deleted national days"); }
}

/* ---- 3. drop bare weekday names ------------------------------------------ */
for (const code of DROP_WEEKDAY_NAMES){
  const data = read(code);
  if (!data) continue;
  let removed = 0, cleaned = 0;
  for (const year in data) for (const key of Object.keys(data[year])){
    const name = String(data[year][key][0]);
    const parts = name.split(";").map(s => s.trim());
    const kept  = parts.filter(s => !WEEKDAY.test(s));
    if (kept.length === 0){ delete data[year][key]; removed++; }
    else if (kept.length !== parts.length){ data[year][key][0] = kept.join("; "); cleaned++; }
  }
  if (removed || cleaned){
    write(code, data); total += removed + cleaned;
    report.push(code + ": removed " + removed + " weekday entries, cleaned " + cleaned + " combined names");
  }
}

/* ------------------------------------------------------------------ output */
if (report.length) report.forEach(r => console.log("  " + r));
console.log("\n  " + (total ? total + " entries corrected" : "nothing to correct, the data is already right"));
console.log("  Now run: node tools/audit-holidays.js");
